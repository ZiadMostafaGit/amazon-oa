"""The study space: the topic canon, its articles, and each topic's problems.

topics/INDEX.json is generated by tools/topicmap.py from the bank plus
tools/canon.py; the articles are Markdown under topics/articles/<slug>.md.
Both are read from disk on demand and cached by mtime, so editing an article
shows up on the next request without restarting the server.

Nothing here writes to the bank. Study state (read / notes) lives in the
progress database next to the rest of the user's data.
"""

from __future__ import annotations

import ast
import json
import os
import random
import re

import mdlite

HERE = os.path.dirname(os.path.abspath(__file__))
INDEX_PATH = os.path.join(HERE, "topics", "INDEX.json")
ARTICLE_DIR = os.path.join(HERE, "topics", "articles")

_cache: dict = {"index": None, "mtime": None, "articles": {}}


# --------------------------------------------------------------------- index
def index() -> dict:
    try:
        m = os.path.getmtime(INDEX_PATH)
    except OSError:
        return {"problems": 0, "topics": [], "byProblem": {}}
    if _cache["index"] is None or _cache["mtime"] != m:
        with open(INDEX_PATH) as fh:
            data = json.load(fh)
        data["bySlug"] = {t["slug"]: t for t in data["topics"]}
        _cache["index"], _cache["mtime"] = data, m
    return _cache["index"]


def topics_for(pid: str) -> list[dict]:
    """The topic links to show under a problem statement."""
    idx = index()
    out = []
    for slug in idx.get("byProblem", {}).get(pid, []):
        t = idx["bySlug"].get(slug)
        if t:
            out.append({"slug": slug, "title": t["title"], "count": t["count"]})
    return out


# ------------------------------------------------------------------ articles
def article_path(slug: str) -> str:
    return os.path.join(ARTICLE_DIR, "%s.md" % slug)


def _clip(text: str, limit: int = 240) -> str:
    """The first sentence or two, never cut mid-word."""
    text = re.sub(r"\s+", " ", re.sub(r"[*`]", "", text)).strip()
    if len(text) <= limit:
        return text
    cut = text[:limit]
    end = max(cut.rfind(". "), cut.rfind("! "), cut.rfind("? "))
    if end > limit // 2:
        return cut[:end + 1]
    return cut[:cut.rfind(" ")] + "…"


def _summary(src: str) -> str:
    quote = []
    for line in src.split("\n"):
        s = line.strip()
        if s.startswith(">"):
            quote.append(s.lstrip("> ").strip())
        elif quote:
            break
    if quote:
        return _clip(" ".join(quote))
    for para in re.split(r"\n\s*\n", src):
        p = para.strip()
        if p and not p.startswith("#"):
            return _clip(p)
    return ""


def article(slug: str) -> dict | None:
    path = article_path(slug)
    try:
        m = os.path.getmtime(path)
    except OSError:
        return None
    hit = _cache["articles"].get(slug)
    if hit and hit["mtime"] == m:
        return hit
    with open(path) as fh:
        src = fh.read()
    # the view prints the title in its own header, so the article's H1 would
    # be a second copy of it; the lede under it stays.
    body = re.sub(r"\A\s*#\s+[^\n]*\n", "", src)
    rendered = mdlite.render(body, lambda s: "?study=" + s)
    words = len(re.findall(r"[A-Za-z0-9'’-]+", re.sub(r"(?s)```.*?```", "", src)))
    for sn in rendered["snippets"]:
        sn["stub"] = stub(sn["code"]) if sn["run"] and sn["lang"] == "python" else None
    out = {"mtime": m, "source": src, "summary": _summary(src), "words": words,
           "html": rendered["html"], "toc": rendered["toc"],
           "snippets": rendered["snippets"], "checks": rendered["checks"]}
    _cache["articles"][slug] = out
    return out


def stub(code: str) -> str | None:
    """The same block with every function body removed, so the reader writes
    it from memory and the block's own asserts grade the attempt. None when
    the block has no function to blank or nothing left to check it with."""
    try:
        tree = ast.parse(code)
    except SyntaxError:
        return None
    funcs = [n for n in tree.body if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef))]
    checks = [n for n in ast.walk(tree) if isinstance(n, ast.Assert)
              and not any(n in ast.walk(f) for f in funcs)]
    if not funcs or not checks:
        return None
    lines = code.split("\n")
    out, skip_to = [], -1
    for n in funcs:
        # keep the signature (and any decorators / docstring), drop the rest
        body = n.body
        if body and isinstance(body[0], ast.Expr) and isinstance(
                getattr(body[0], "value", None), ast.Constant) and isinstance(body[0].value.value, str):
            body = body[1:]
        if not body:
            continue
        first, last = body[0].lineno, n.end_lineno
        indent = " " * body[0].col_offset
        lines[first - 1:last] = [indent + "...  # write it from memory; the asserts below grade you"] + \
                                [None] * (last - first)
    out = [l for l in lines if l is not None]
    return "\n".join(out)


def has_article(slug: str) -> bool:
    return os.path.isfile(article_path(slug))


