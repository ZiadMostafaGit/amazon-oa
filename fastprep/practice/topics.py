_SUBJECT_BY_NAME = {name: (slug, blurb) for name, slug, blurb in SUBJECTS}
_SUBJECT_BY_SLUG = {slug: name for name, slug, _ in SUBJECTS}


def _slugify(name: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def _learning_order(ts: list[dict]) -> list[tuple[dict, int]]:
    """The subject as a tree, walked in preorder: each chapter files under the
    most specific chapter it needs inside the subject (the least-used of its
    prerequisites here), chapters that need nothing here are roots, and
    siblings go most-used first. So Graphs reads graphs > dfs > topological
    sort > ... > bfs > grid bfs > flood fill ..., and Dynamic Programming puts
    LIS and Kadane under one-dimensional DP rather than wherever their counts
    happen to fall. Returns (chapter, depth)."""
    here = {t["slug"]: t for t in ts}
    kids: dict[str | None, list[dict]] = {}
    for t in ts:
        needs = [here[n] for n in t["needs"] if n in here and n != t["slug"]]
        parent = min(needs, key=lambda n: (n["count"], n["slug"]))["slug"] if needs else None
        kids.setdefault(parent, []).append(t)
    for v in kids.values():
        v.sort(key=lambda t: (-t["count"], t.get("kind") == "method", t["title"]))
    out, seen = [], set()

    def walk(parent, depth):
        for t in kids.get(parent, []):
            if t["slug"] in seen:
                continue
            seen.add(t["slug"])
            out.append((t, depth))
            walk(t["slug"], depth + 1)
    walk(None, 0)
    for t in ts:                              # a cycle in the canon: flush it
        if t["slug"] not in seen:
            seen.add(t["slug"]); out.append((t, 0))
    return out


def subjects() -> list[dict]:
    """Every subject with its chapters in learning order; cached on the index."""
    idx = index()
    if "subjects" in idx:
        return idx["subjects"]
    groups: dict[str, list[dict]] = {}
    for t in idx["topics"]:
        groups.setdefault(t["category"], []).append(t)
    known = [name for name, _, _ in SUBJECTS if name in groups]
    extra = sorted((n for n in groups if n not in _SUBJECT_BY_NAME),
                   key=lambda n: -sum(t["count"] for t in groups[n]))
    out = []
    for name in known + extra:
        ordered = _learning_order(groups[name])
        slug, blurb = _SUBJECT_BY_NAME.get(name, (_slugify(name), ""))
        union: set[str] = set()
        for t, _ in ordered:
            union.update(t.get("problems") or [])
        out.append({"slug": slug, "name": name, "blurb": blurb,
                    "chapters": [t["slug"] for t, _ in ordered],
                    "depth": {t["slug"]: d for t, d in ordered},
                    "count": len(union), "problemIds": union})
    idx["subjects"] = out
    idx["subjectBySlug"] = {s["slug"]: s for s in out}
    return out


# ------------------------------------------------------------------- mastery
MASTERY_SOLVED = 3     # queue problems solved before a chapter counts as practised


def mastery(t: dict, a: dict | None, st: dict, solved: int) -> dict:
    """Five things, each either done or not: tried a problem before reading,
    read the chapter, wrote the implementation back from memory, told the
    topic apart from its neighbours, and solved enough of its queue. "Read"
    alone was the old status; it is the weakest of the five."""
    extra = st.get("extra") or {}
    recall = extra.get("recall") or {}
    drill = extra.get("drill") or {}
    has_queue = bool(t.get("count")) and t.get("kind") != "craft"
    steps = {
        "tried": bool(extra.get("tried") and not extra["tried"].get("skipped")) if has_queue else None,
        "read": st.get("status") == "done",
        "recalled": any(recall.values()) if (a and any(sn.get("stub") for sn in a["snippets"])) else None,
        "drilled": (drill.get("score", 0) >= max(1, drill.get("total", 0) - 1)
                    and drill.get("total", 0) > 0) if has_queue else None,
        "solved": solved >= MASTERY_SOLVED if has_queue else None,
    }
    counted = [v for v in steps.values() if v is not None]
    return {"steps": steps, "done": sum(1 for v in counted if v), "of": len(counted),
            "solved": solved, "solvedOf": MASTERY_SOLVED}


# ------------------------------------------------------------------ listings
def listing(progress=None, bank=None) -> dict:
    """Every topic, ranked, with how far the reader has got."""
    idx = index()
    studied = progress.topics_all() if progress else {}
    solved = set(progress.ids_with(status="solved")) if progress else set()
    out = []
    for t in idx["topics"]:
        a = article(t["slug"])
        ids = t.get("problems") or []
        st = studied.get(t["slug"]) or {}
        out.append({
            "slug": t["slug"], "title": t["title"], "category": t["category"],
            "rank": t["rank"], "count": t["count"], "rare": t["rare"],
            "kind": t.get("kind", "topic"),
            "needs": t["needs"], "near": t["near"], "covers": t.get("covers") or [],
            "summary": (a or {}).get("summary", ""),
            "words": (a or {}).get("words", 0),
            "hasArticle": a is not None,
            "solved": sum(1 for i in ids if i in solved),
            "status": st.get("status"),
            "mastery": mastery(t, a, st, sum(1 for i in ids if i in solved)),
        })
    by_slug = {t["slug"]: t for t in out}
    subs = []
    for s in subjects():
        chapters = [by_slug[c] for c in s["chapters"] if c in by_slug]
        subs.append({"slug": s["slug"], "name": s["name"], "blurb": s["blurb"],
                     "chapters": [{"slug": c["slug"], "depth": s["depth"][c["slug"]]}
                                  for c in chapters],
                     "count": s["count"],
                     "solved": sum(1 for i in s["problemIds"] if i in solved),
                     "written": sum(1 for c in chapters if c["hasArticle"]),
                     "done": sum(1 for c in chapters if c["status"] == "done"),
                     "mastered": sum(1 for c in chapters
                                     if c["mastery"]["of"] and c["mastery"]["done"] == c["mastery"]["of"])})
    cats = [s["name"] for s in subs]
    return {"topics": out, "categories": cats, "subjects": subs,
            "problems": idx.get("problems", 0),
            "withArticles": sum(1 for t in out if t["hasArticle"])}


def subject_detail(slug: str, bank=None, progress=None, queue_limit: int = 120) -> dict | None:
    """One subject: its chapters as a learning path, what it leans on from
    other subjects, what elsewhere leans on it, and one practice queue over
    every problem any of its chapters uses."""
    subjects()
    idx = index()
    s = idx["subjectBySlug"].get(slug)
    if not s:
        return None
    here = set(s["chapters"])
    studied = progress.topics_all() if progress else {}
    solved = set(progress.ids_with(status="solved")) if progress else set()
    chapters = []
    for c in s["chapters"]:
        t = idx["bySlug"][c]
        a = article(c)
        ids = t.get("problems") or []
        st = studied.get(c) or {}
        chapters.append({
            "slug": c, "title": t["title"], "rank": t["rank"], "count": t["count"],
            "depth": s["depth"][c],
            "rare": t["rare"], "kind": t.get("kind", "topic"),
            "covers": t.get("covers") or [],
            "needs": [n for n in t["needs"] if n in here],
            "summary": (a or {}).get("summary", ""),
            "words": (a or {}).get("words", 0),
            "hasArticle": a is not None,
            "solved": sum(1 for i in ids if i in solved),
            "status": st.get("status"),
            "mastery": mastery(t, a, st, sum(1 for i in ids if i in solved)),
        })

    def brief(o):
        return {"slug": o["slug"], "title": o["title"], "count": o["count"],
                "subject": _SUBJECT_BY_NAME.get(o["category"], (_slugify(o["category"]),))[0],
                "subjectName": o["category"], "hasArticle": has_article(o["slug"])}

    # what you should know first, from other subjects
    before, seen = [], set()
    for c in s["chapters"]:
        for n in idx["bySlug"][c]["needs"]:
            o = idx["bySlug"].get(n)
            if o and n not in here and n not in seen:
                seen.add(n); before.append(brief(o))
    # chapters filed elsewhere that build on this subject (tree DP under
    # Trees, Floyd-Warshall under Graphs, ...), so "everything about DP" is
    # really everything
    beyond, seen = [], set()
    for t in idx["topics"]:
        if t["slug"] in here or t["slug"] in seen:
            continue
        if any(n in here for n in list(t["needs"]) + list(t["near"])):
            seen.add(t["slug"]); beyond.append(brief(t))
    beyond.sort(key=lambda b: -b["count"])

    # one queue over the whole subject: a problem that several chapters
    # claim is more "about" the subject than one claimed by a single stray
    # match, so it sorts first; then the chapter's own easiest-first order
    score: dict[str, list] = {}
    for c in s["chapters"]:
        for pos, pid in enumerate(idx["bySlug"][c].get("problems") or []):
            e = score.setdefault(pid, [0, pos])
            e[0] += 1
            e[1] = min(e[1], pos)
    ordered = sorted(score, key=lambda p: (-score[p][0], score[p][1], p))[:queue_limit]
    queue = []
    if ordered and bank is not None:
        rows = {r["id"]: r for r in bank.query({"ids": ordered}, sort="default",
                                               limit=len(ordered)).get("items", [])}
        try:
            import solutions
            verified = solutions.verified_ids()
        except Exception:
            verified = set()
        for i in ordered:
            r = rows.get(i)
            if not r:
                continue
            p = progress.get(i) if progress is not None else None
            p = p or {}
            queue.append({"id": i, "title": r["title"], "difficulty": r["difficulty"],
                          "company": r["company"], "seenCount": r["seenCount"],
                          "status": p.get("status"), "hasSolution": i in verified,
                          "chapters": score[i][0]})
    # what goes wrong for you in this subject, from your own post-mortems,
    # and which of its problems are owed a re-solve
    mistakes: dict[str, int] = {}
    due = []
    if progress is not None:
        for pid, kind in progress.mistakes().items():
            if pid in s["problemIds"] and kind not in ("", "none"):
                mistakes[kind] = mistakes.get(kind, 0) + 1
        for r in progress.reviews()["due"]:
            if r["id"] in s["problemIds"]:
                d = bank.detail(r["id"]) if bank is not None else None
                due.append(dict(r, title=(d or {}).get("title") or r["id"]))
    return {
        "slug": slug, "name": s["name"], "blurb": s["blurb"],
        "count": s["count"], "problems": idx.get("problems", 0),
        "solved": sum(1 for i in s["problemIds"] if i in solved),
        "chapters": chapters, "before": before, "beyond": beyond,
        "queue": queue, "queueTotal": len(score),
        "mistakes": sorted(mistakes.items(), key=lambda kv: -kv[1]),
        "reviewsDue": due,
    }


def detail(slug: str, bank=None, progress=None, queue_limit: int = 400) -> dict | None:
    idx = index()
    t = idx["bySlug"].get(slug)
    if not t:
        return None
    a = article(slug)
    ids = (t.get("problems") or [])[:queue_limit]
    queue = []
    if ids and bank is not None:
        rows = {r["id"]: r for r in bank.query({"ids": ids}, sort="default",
                                               limit=len(ids)).get("items", [])}
        prog = {}
        if progress is not None:
            prog = {i: progress.get(i) for i in ids if i in rows}
        try:
            import solutions
            verified = solutions.verified_ids()
        except Exception:
            verified = set()
        for i in ids:
            r = rows.get(i)
            if not r:
                continue
            p = prog.get(i) or {}
            queue.append({"id": i, "title": r["title"], "difficulty": r["difficulty"],
                          "company": r["company"], "seenCount": r["seenCount"],
                          "status": p.get("status"), "hasSolution": i in verified})
    st = progress.topic_get(slug) if progress is not None else {}
    solved_n = sum(1 for q in queue if q["status"] == "solved")
    related = []
    for s in list(t["needs"]) + list(t["near"]):
        o = idx["bySlug"].get(s)
        if o and all(r["slug"] != s for r in related):
            related.append({"slug": s, "title": o["title"], "count": o["count"],
                            "kind": "prerequisite" if s in t["needs"] else "next",
                            "hasArticle": has_article(s)})
    return {
        "slug": slug, "title": t["title"], "category": t["category"],
        "subject": _SUBJECT_BY_NAME.get(t["category"], (_slugify(t["category"]),))[0],
        "rank": t["rank"], "count": t["count"], "rare": t["rare"],
        "kind": t.get("kind", "topic"), "covers": t.get("covers") or [],
        "related": related,
        "article": None if a is None else {
            "html": a["html"], "toc": a["toc"], "words": a["words"],
            "checks": a["checks"], "summary": a["summary"],
            "snippets": [{"lang": s["lang"], "run": s["run"], "code": s["code"],
                          "stub": s.get("stub")}
                         for s in a["snippets"]],
        },
        "queue": queue, "queueTotal": t["count"],
        "tryFirst": try_first(queue, st),
        "drill": drill(slug, bank) if bank is not None and t.get("kind") != "craft" else [],
        "mastery": mastery(t, a, st, solved_n),
        "study": st,
    }


def try_first(queue: list[dict], st: dict) -> dict | None:
    """The problem to attempt BEFORE reading: the one you already tried if
    there is one, else the easiest unsolved problem with a reference solution
    so the attempt can be checked, else the easiest unsolved one."""
    if not queue:
        return None
    tried = ((st.get("extra") or {}).get("tried") or {}).get("pid")
    for q in queue:
        if q["id"] == tried:
            return q
    fresh = [q for q in queue if q["status"] != "solved"]
    for q in fresh:
        if q["hasSolution"]:
            return q
    return (fresh or queue)[0]


DRILL_SIZE = 4     # of the topic, and as many decoys


def drill(slug: str, bank, size: int = DRILL_SIZE) -> list[dict]:
    """Recognition: a mix of this topic's problems and problems from its
    neighbours that are NOT this topic, title and opening lines only. Telling
    them apart is the interview skill, and no chapter can do it for you."""
    idx = index()
    t = idx["bySlug"].get(slug)
    if not t:
        return []
    mine = [p for p in (t.get("problems") or [])[:40]]
    here = set(t.get("problems") or [])
    pool = []
    for n in list(t["near"]) + list(t["needs"]):
        o = idx["bySlug"].get(n)
        for p in (o.get("problems") or [])[:40] if o else []:
            if p not in here and p not in pool:
                pool.append(p)
    rng = random.Random()
    picks = [(p, True) for p in rng.sample(mine, min(size, len(mine)))]
    picks += [(p, False) for p in rng.sample(pool, min(size, len(pool)))]
    rng.shuffle(picks)
    out = []
    for pid, yes in picks:
        d = bank.detail(pid)
        if not d:
            continue
        text = _text(d.get("problemStatement") or "")
        out.append({"id": pid, "title": d.get("title") or pid, "isTopic": yes,
                    "excerpt": _clip(text, 320),
                    "difficulty": d.get("difficulty"), "company": d.get("company")})
    return out


def _text(html: str) -> str:
    html = re.sub(r"(?is)<(script|style).*?</\1>", " ", html)
    html = re.sub(r"(?i)<br\s*/?>|</p>|</li>|</div>", " ", html)
    text = re.sub(r"<[^>]+>", "", html)
    text = (text.replace("&nbsp;", " ").replace("&lt;", "<").replace("&gt;", ">")
                .replace("&amp;", "&").replace("&quot;", '"').replace("&#39;", "'"))
    return re.sub(r"\s+", " ", text).strip()


# ------------------------------------------------------------------- reviews
def reviews(progress, bank=None) -> dict:
    """Spaced re-solves owed now, with titles and the subject each belongs to."""
    out = progress.reviews()
    subjects()
    idx = index()
    by_problem = idx.get("byProblem", {})
    for r in out["due"]:
        d = bank.detail(r["id"]) if bank is not None else None
        r["title"] = (d or {}).get("title") or r["id"]
        r["difficulty"] = (d or {}).get("difficulty")
        slugs = by_problem.get(r["id"]) or []
        sub = next((s for s in idx["subjects"] if slugs and slugs[0] in s["depth"]), None)
        r["subject"] = sub["name"] if sub else None
    return out


def mixed_pick(progress, bank=None) -> dict:
    """One problem from the subjects you have started, chosen so you do not
    know which tool it wants: blocked practice teaches the tool, mixed
    practice teaches choosing it, and interviews are the second kind."""
    subjects()
    idx = index()
    started = {s["slug"] for s in idx["subjects"]
               if any(c in progress.topics_all() for c in s["chapters"])}
    if not started:
        return {"problem": None, "subjects": [], "reason": "no subject started yet"}
    solved = set(progress.ids_with(status="solved"))
    pool = []
    for s in idx["subjects"]:
        if s["slug"] in started:
            pool.extend(p for p in s["problemIds"] if p not in solved)
    pool = sorted(set(pool))
    names = sorted(s["name"] for s in idx["subjects"] if s["slug"] in started)
    if not pool:
        return {"problem": None, "subjects": names, "reason": "everything in them is solved"}
    pid = random.choice(pool)
    d = bank.detail(pid) if bank is not None else None
    return {"problem": {"id": pid, "title": (d or {}).get("title") or pid,
                        "difficulty": (d or {}).get("difficulty")},
            "subjects": names, "pool": len(pool)}
